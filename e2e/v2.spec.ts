test('backup preview and integrity check do not apply an import', async ({ page }, info) => {
  await onboard(page)
  await logFood(page, 'arroz cocido', '100')
  await page.goto('./#/respaldo')
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByTestId('export-profile').click()])
  const path = info.outputPath('v2-preview.json')
  await download.saveAs(path)
  const backup = JSON.parse(await readFile(path, 'utf8'))
  expect(backup.tables.foodLogs).toHaveLength(1)
  await page.getByTestId('import-backup-file').setInputFiles(path)
  await expect(page.getByTestId('import-preview')).toBeVisible()
  await expect(page.getByTestId('import-preview')).toContainText('Registros de comida')
  await expect(page.getByTestId('import-result')).toHaveCount(0)
  // "Verificar datos" lives inside the closed "Herramientas avanzadas" disclosure (V3.1).
  await page.getByTestId('backup-advanced').getByText('Herramientas avanzadas').click()
  await page.getByTestId('integrity-run').click()
  await expect(page.getByTestId('integrity-ok')).toContainText('Todo en orden')
})

