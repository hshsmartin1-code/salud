test('empty control center and health hub show real empty states', async ({ page }) => {
  await onboard(page)
  await expect(page.getByTestId('hoy-empty')).toBeVisible() // fresh profile: a short empty state, no rings
  await expect(page.getByTestId('day-summary')).toHaveCount(0)
  await expect(page.getByTestId('range-stats')).toHaveCount(0) // no data in either week: not rendered
  await page.getByRole('navigation', { name: 'Principal' }).getByRole('link', { name: 'Salud' }).click()
  await expect(page.getByTestId('health-hub')).toBeVisible()
  const hub = page.getByTestId('health-hub')
  // A brand-new profile: one explanatory sentence, the quick actions, no empty charts.
  await expect(hub.getByTestId('hub-empty')).toContainText('Tus tendencias aparecerán aquí')
  await expect(page.getByTestId('chart-panel')).toHaveCount(0)
  for (const name of ['Peso', 'Agua', 'Sueño', 'Presión', 'Más']) await expect(hub.getByTestId('quick-log').getByRole('button', { name })).toBeVisible()
  for (const title of ['Hábitos y suplementos', 'Fotos de progreso', 'Health Connect']) await expect(hub.getByRole('link', { name: new RegExp(title) })).toBeVisible()
  await expect(hub.getByTestId('hub-health-connect')).toBeVisible()
})

