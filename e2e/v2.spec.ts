test('mobile registration sheet traps Tab and Escape restores its trigger', async ({ page }) => {
  await onboard(page)
  const trigger = page.getByRole('navigation', { name: 'Principal' }).getByRole('button', { name: 'Registrar' })
  await trigger.focus()
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: 'Registrar' })
  await expect(dialog).toBeVisible()
  const close = dialog.getByRole('button', { name: 'Cerrar' })
  await close.focus()
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: /Foto de progreso/ })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(close).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()
})
