test('water goal, quick add, custom add, undo and dashboard stay in sync', async ({ page }) => {
  await onboard(page)
  await page.goto('./#/agua')
  await expect(page.getByTestId('hydration-today')).toContainText('0')
  await page.getByTestId('set-water-goal').click()
  await page.getByLabel('Meta diaria').fill('2000')
  await page.getByTestId('save-water-goal').click()
  await expect(page.getByTestId('hydration-page')).toContainText('Meta 2.000 ml')
  await page.getByTestId('add-water-250').click()
  await expect(page.getByTestId('hydration-today')).toContainText('250')
  await page.getByTestId('add-water-custom').click()
  await page.getByLabel('Cantidad').fill('350')
  await page.getByTestId('save-water-custom').click()
  await expect(page.getByTestId('hydration-today')).toContainText('600')
  await expect(page.locator('.toast-host')).toContainText('+350 ml de agua')
  await clickUndo(page)
  await expect(page.getByTestId('hydration-today')).toContainText('250')
  await expect(page.getByTestId('hydration-today')).not.toContainText('600')
  await page.goto('./')
  await expect(page.getByRole('link', { name: /Agua/ }).first()).toContainText('0,25')
  await page.goto('./#/agua')
  await expect(page.getByTestId('water-entries')).toContainText('250 ml')
})

